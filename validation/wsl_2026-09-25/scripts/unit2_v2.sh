#!/bin/bash
# unit2_v2.sh -- v1 unit2.sh with PLAN/SP as parameters (default PLAN: the edited D:\BEN\FEMTIC_2026\hpc\phoenix_plan); checks unchanged.
PLAN=${PLAN:-/mnt/d/BEN/FEMTIC_2026/hpc/phoenix_plan}
SP=${SP:-/mnt/c/Users/joint/AppData/Local/Temp/claude/D--BEN-FEMTIC-2026/4e858f54-ea4e-47a8-9815-7766aca9830d/scratchpad}
. $PLAN/femtic_lib.sh
fail=0; chk(){ if [ "$2" = "$3" ]; then echo "  PASS $1 ($2)"; else echo "  FAIL $1: got '$2' want '$3'"; fail=1; fi; }
W=$(mktemp -d); mkdir -p $W/straight $W/restart
# the function body is taken verbatim from 01_build_femtic.sh
sed -n '/^  cmp_misfit() {/,/^  }/p' $PLAN/01_build_femtic.sh > $W/cmp.sh
chk extracted_lines "$( [ $(wc -l < $W/cmp.sh) -gt 10 ] && echo ok)" ok
. $W/cmp.sh
H='     Iter#  Retrial#          Alpha           Damp      Roughness         Misfit            RMS        ObjFunc'
mk(){ printf '%s\n' "$H" "$@"; }
row(){ printf '%10d%10d%15e%15e%15e%15e%15e%15e' "$@"; }
echo "T5a identical -> PASS"
mk "$(row 0 0 1 0.5 0 1000 2 1000)" "$(row 1 0 1 0.5 1 500 1.5 501)" "$(row 2 0 1 0.5 1 300 1.2 301)" > $W/straight/femtic.cnv.straight
mk "$(row 1 0 1 0.5 1 500 1.5 501)" "$(row 2 0 1 0.5 1 300 1.2 301)" > $W/restart/femtic.cnv.leg2
T5=PASS; cmp_misfit 1 1e-4 >/dev/null; cmp_misfit 2 1e-3 >/dev/null; chk T5a "$T5" PASS
echo "T5b small rounding (2e-5 at iter 1, 5e-4 at iter 2) -> PASS"
mk "$(row 1 0 1 0.5 1 500.01 1.5 501)" "$(row 2 0 1 0.5 1 300.15 1.2 301)" > $W/restart/femtic.cnv.leg2
T5=PASS; cmp_misfit 1 1e-4 >/dev/null; cmp_misfit 2 1e-3 >/dev/null; chk T5b "$T5" PASS
echo "T5c restart from the wrong model (misfit of iter 0 at iter 1) -> FAIL"
mk "$(row 1 0 1 0.5 1 1000 2 1000)" "$(row 2 0 1 0.5 1 500 1.5 501)" > $W/restart/femtic.cnv.leg2
T5=PASS; cmp_misfit 1 1e-4 >/dev/null; cmp_misfit 2 1e-3 >/dev/null; chk T5c "$T5" FAIL
echo "T5d retrial in straight run at iter 2 -> INCONCLUSIVE (not PASS, not FAIL)"
mk "$(row 0 0 1 0.5 0 1000 2 1000)" "$(row 1 0 1 0.5 1 500 1.5 501)" "$(row 2 0 1 0.5 1 600 1.6 601)" "$(row 2 1 1 0.25 1 400 1.3 401)" > $W/straight/femtic.cnv.straight
mk "$(row 1 0 1 0.5 1 500 1.5 501)" "$(row 2 0 1 0.5 1 300 1.2 301)" > $W/restart/femtic.cnv.leg2
T5=PASS; cmp_misfit 1 1e-4 >/dev/null; cmp_misfit 2 1e-3 >/dev/null; chk T5d "$T5" INCONCLUSIVE
echo "T5e missing restart row -> FAIL"
mk "$(row 1 0 1 0.5 1 500 1.5 501)" > $W/restart/femtic.cnv.leg2
T5=PASS; cmp_misfit 1 1e-4 >/dev/null; cmp_misfit 2 1e-3 >/dev/null; chk T5e "$T5" FAIL
echo "03 region-attribute check (code copied from 03_mesh.slurm) against femticPy synthetic resistivity_attr.dat"
sed 's/\r$//' $SP/femticPy/projects/synthetic/meshGen/files/resistivity_attr.dat > $W/attr.dat 2>/dev/null || printf '2\n10 1.0e+9 -1 1\n20 100.0   9 0\n' > $W/attr.dat
NATTR=$(head -1 $W/attr.dat | awk '{print $1}')
ATTRS=$(awk -v n="$NATTR" 'NR>1 && NR<=n+1 {print $1}' $W/attr.dat | sort -u | tr '\n' ' ')
chk attrs "$ATTRS" "10 20 "
REGIONS=$'1   0.0 0.0 -40.0   10 1e9\n2   0.0 0.0  10.0   20 1e9'
ok=yes; for a in $(echo "$REGIONS" | awk '{print $5}'); do echo " $ATTRS " | grep -q " $a " || ok=no; done; chk default_regions_ok "$ok" yes
REGIONS=$'1 0 0 -40 10 1e9\n2 0 0 10 30 1e9'
ok=yes; for a in $(echo "$REGIONS" | awk '{print $5}'); do echo " $ATTRS " | grep -q " $a " || ok=no; done; chk attr30_rejected "$ok" no
echo "03 output.poly region-count replacement (meshGen.sh logic) on a poly ending '# Part 4' / '0'"
printf '# Part 3\n0\n# Part 4\n0\n' > $W/output.poly; NREG=2
sed -i "$(( $(wc -l < $W/output.poly) ))s/.*/$NREG/" $W/output.poly; echo "$REGIONS" >> $W/output.poly
chk poly "$(sed -n '3,6p' $W/output.poly | tr '\n' '|')" "# Part 4|2|1 0 0 -40 10 1e9|2 0 0 10 30 1e9|"
echo "03 FIX_ELE awk on a tetgen-style .ele"
printf '3  4  1\n    0  1 2 3 4  10\n    1  1 2 3 5  40\n    2  2 3 4 5  30\n# Generated by tetgen -nVpYAakq3.0/0 output.poly\n' > $W/output.1.ele
awk -v m=30 'NR==1 {print; next} /^[[:space:]]*#/ {next} {if ($6 > m) $6 = m; print}' $W/output.1.ele > $W/fix.ele
chk fix_ele "$(awk 'NR>1{print $6}' $W/fix.ele | tr '\n' ' ')" "10 30 30 "; chk fix_ele_lines "$(wc -l < $W/fix.ele)" 4
echo; echo "OVERALL: $([ $fail = 0 ] && echo PASS || echo FAIL)"; rm -rf $W
