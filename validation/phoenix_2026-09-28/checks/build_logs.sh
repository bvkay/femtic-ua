#!/usr/bin/env bash
# Check e (build logs) and the B2 grep criteria of RUNBOOK_first_inversion.md, on the copies in this folder.
# Run from the repository root:  bash validation/phoenix_2026-09-28/checks/build_logs.sh
set -u
REPO=$(git rev-parse --show-toplevel) || exit 1
EV=$REPO/validation/phoenix_2026-09-28
B0925=$REPO/hpc/phoenix_plan/build_foss_20260925_181212.log      # 09-25 18:12 login-node build (fa58604 kit)
B0928=$EV/build_foss_20260928_211021.log                         # 09-28 21:10 login-node rebuild (HEAD kit)
OUT=$EV/slurm-femtic_smoke-16153670.out
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
PASS=0; FAIL=0
chk() { if [ -n "$2" ] && [ "$2" = "$3" ]; then printf '  PASS %-66s [%s]\n' "$1" "$2"; PASS=$((PASS+1));
        else printf '  FAIL %-66s got [%s] expected [%s]\n' "$1" "$2" "$3"; FAIL=$((FAIL+1)); fi; }
lsz() { awk -v n="$2" '$1 ~ /^-r/ && $NF == n {print $5}' "$1"; }   # size of <name> in a log's 'ls -l' listing

echo "== e1. This test fails if a binary's size in the 09-28 build listing differs from the 09-25 18:12 listing."
echo "-- fail case: the same comparison on the two files the kit changed between the builds (must FAIL)"
F0=$FAIL
for n in femtic_env.sh femtic_lib.sh; do chk "09-28 vs 09-25 size of $n" "$(lsz "$B0928" $n)" "$(lsz "$B0925" $n)"; done
FC1=$((FAIL - F0)); FAIL=$F0
echo "-- real: the seven binaries"
for n in femtic makeTetraMesh makeMtr TetGen2Femtic makeDHexaMesh mergeResultOfFEMTIC tetgen; do
  chk "09-28 vs 09-25 size of $n" "$(lsz "$B0928" $n)" "$(lsz "$B0925" $n)"
done
echo "-- the smoke job's own listing of \$BIN (written on the compute node 2 min later) vs the 09-28 build log"
for n in femtic femtic_env.sh femtic_lib.sh tetgen; do chk "smoke vs build size of $n" "$(lsz "$OUT" $n)" "$(lsz "$B0928" $n)"; done

echo; echo "== e2. This test fails if femtic_env.sh (09-28) is not the size the HEAD writer produces, or 09-25's not fa58604's."
S=0
for c in fa58604 55bbf44; do
  git -C "$REPO" show $c:hpc/phoenix_plan/01_build_femtic.sh > "$T/01_$c.sh"
  a=$(grep -n '^{$' "$T/01_$c.sh" | awk -F: '{print $1}' | while read -r l; do sed -n "$((l+1))p" "$T/01_$c.sh" | grep -q 'generated by 01_build_femtic.sh' && echo "$l"; done | head -1)
  b=$(awk -v s="$a" 'NR > s && /^} > "\$BIN\/femtic_env.sh"/ {print NR; exit}' "$T/01_$c.sh")
  { echo "date() { echo 'Mon Sep 28 21:11:14 ACST 2026'; }"     # same length as every 'date' of both build logs
    echo 'BIN=/hpcfs/users/a1690074/femtic/bin TOOLCHAIN=foss MODS="foss/2023a imkl/2023.1.0" EB_MODULES=/hpcfs/users/a1690074/easybuild/modules/all'
    sed -n "${a},${b}p" "$T/01_$c.sh" | sed 's#> "$BIN/femtic_env.sh"#> "$OUTF"#'; } > "$T/gen_$c.sh"
  OUTF=$T/env_$c.txt bash "$T/gen_$c.sh"
  eval "SZ_$c=$(wc -c < "$T/env_$c.txt")"
done
echo "   reconstructed from the writers (lines of 01_build_femtic.sh at each commit): fa58604 -> $SZ_fa58604 B, 55bbf44 (HEAD) -> $SZ_55bbf44 B"
echo "-- fail case: the 09-28 file against the fa58604 writer (must FAIL)"
F0=$FAIL; chk "09-28 femtic_env.sh size = fa58604 writer" "$(lsz "$B0928" femtic_env.sh)" "$SZ_fa58604"; FC2=$((FAIL - F0)); FAIL=$F0
chk "09-28 femtic_env.sh size = HEAD writer" "$(lsz "$B0928" femtic_env.sh)" "$SZ_55bbf44"
chk "09-25 femtic_env.sh size = fa58604 writer" "$(lsz "$B0925" femtic_env.sh)" "$SZ_fa58604"
chk "09-28 femtic_lib.sh size = git show 55bbf44 (HEAD)" "$(lsz "$B0928" femtic_lib.sh)" "$(git -C "$REPO" show 55bbf44:hpc/phoenix_plan/femtic_lib.sh | wc -c)"
chk "09-25 femtic_lib.sh size = git show fa58604" "$(lsz "$B0925" femtic_lib.sh)" "$(git -C "$REPO" show fa58604:hpc/phoenix_plan/femtic_lib.sh | wc -c)"
chk "worktree femtic_lib.sh is NOT what ran (size differs from 19992)" "$( [ "$(wc -c < "$REPO/hpc/phoenix_plan/femtic_lib.sh")" != 19992 ] && echo yes)" yes

echo; echo "== e3. Same source and toolchain: this test fails if the commits, the module list, the compile commands or the"
echo "   warnings differ between the 09-25 18:12 and 09-28 21:10 build logs (order-independent; make -j reorders lines)."
chk "source commits" "$(grep -E '^-- [A-Za-z0-9]+ @ ' "$B0928" | tr '\n' ' ')" "$(grep -E '^-- [A-Za-z0-9]+ @ ' "$B0925" | tr '\n' ' ')"
chk "modules (lines 1-24 of 'Currently Loaded Modules')" "$(grep -E '^ +[0-9]+\)' "$B0928" | md5sum | cut -c1-8)" "$(grep -E '^ +[0-9]+\)' "$B0925" | md5sum | cut -c1-8)"
chk "compile/link commands (sorted)" "$(grep -E '^(mpicxx|g\+\+) ' "$B0928" | sort | md5sum | cut -c1-8) n=$(grep -cE '^(mpicxx|g\+\+) ' "$B0928")" "$(grep -E '^(mpicxx|g\+\+) ' "$B0925" | sort | md5sum | cut -c1-8) n=$(grep -cE '^(mpicxx|g\+\+) ' "$B0925")"
chk "compiler warnings (count)" "$(grep -c 'warning:' "$B0928")" "$(grep -c 'warning:' "$B0925")"
echo "-- fail case: the same sorted-command comparison against the 09-25 19:44 icelake log (stopped before compiling)"
F0=$FAIL; chk "compile/link commands vs 09-25 19:44" "$(grep -cE '^(mpicxx|g\+\+) ' "$EV/build_foss_20260925_194435.log")" "$(grep -cE '^(mpicxx|g\+\+) ' "$B0925")"; FC3=$((FAIL - F0)); FAIL=$F0

echo; echo "== e4. What stopped the two 09-25 evening attempts (fa58604 kit; its 01 line 176 is the COMMIT_SHA.txt read)"
for f in build_foss_20260925_193715.log build_foss_20260925_194435.log; do
  echo "-- $f"; head -1 "$EV/$f" | cut -c1-40; grep -oE 'host=[^ ]+  job=[^ ]+ partition=[^ ]+' "$EV/$f"
  grep -E '^(ERROR|WARNING)' "$EV/$f" | cut -c1-110; echo "   last line: $(tail -1 "$EV/$f")"
done

echo; echo "== B2 criteria (RUNBOOK B2 'Fails if'), on the job output"
echo "-- fail case: the DONE grep on the 09-28 build log (a BUILD line, not SMOKE_ONLY) must give 0"
FC4=$(grep -cE '^== .*  SMOKE_ONLY DONE  T1=PASS  T2=PASS  T5=(PASS|INCONCLUSIVE)   log: ' "$B0928")
echo "  build log count = $FC4 (0 expected: the criterion '= 1' FAILS there)"
chk "SMOKE_ONLY DONE grep on slurm-femtic_smoke-16153670.out" "$(grep -cE '^== .*  SMOKE_ONLY DONE  T1=PASS  T2=PASS  T5=(PASS|INCONCLUSIVE)   log: ' "$OUT")" 1
chk "slurm .out byte-identical to smoke_foss_20260928_211308.log" "$(cmp -s "$OUT" "$EV/smoke_foss_20260928_211308.log" && echo yes)" yes
echo "  sacct ExitCode 0:0: NOT in the copied files (no sacct/rcstat output was copied) - unverified"

echo; echo "SUMMARY build_logs: fail cases FAIL as designed: e1 $FC1/2, e2 $FC2/1, e3 $FC3/1, B2 grep on build log gave $FC4 (0);"
echo "  real checks $PASS passed, $FAIL failed"
[ "$FC1" = 2 ] && [ "$FC2" = 1 ] && [ "$FC3" = 1 ] && [ "$FC4" = 0 ] && [ "$FAIL" = 0 ]
