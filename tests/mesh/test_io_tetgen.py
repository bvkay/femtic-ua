import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _common as C  # noqa: E402
import numpy as np  # noqa: E402
from femtic_mesh.io import tetgen as T  # noqa: E402

RW = {"node": (T.read_node, T.write_node), "ele": (T.read_ele, T.write_ele),
      "face": (T.read_face, T.write_face), "neigh": (T.read_neigh, T.write_neigh)}


def _log_stats(path):
    txt = open(path).read()
    g = lambda k: int(re.search(k + r":\s+(\d+)", txt)[1])  # noqa: E731
    return {"points": g("Mesh points"), "tets": g("Mesh tetrahedra"), "facets": g("Mesh faces on input facets"),
            "hull": g("Mesh faces on exterior boundary"), "in_points": g("Input points"),
            "in_facets": g("Input facets"), "in_regions": g("Input regions")}


def test_tetgen_roundtrip_round0():
    """This test fails if any of output.1.{node,ele,face,neigh} (conda-forge tetgen's own files, CRLF and the
    '# Generated by' line included) is not rewritten byte for byte from what the reader returned.

    Negative controls: rewriting after a one-ulp change of one node coordinate (%.17g must show it) and after
    one face marker change must each differ from tetgen's file."""
    with C.tmpdir() as d:
        prefix = C.unpack_fixture(d)
        nd = T.read_node(prefix + ".node")
        nd.xyz[5, 0] = np.nextafter(nd.xyz[5, 0], np.inf)
        T.write_node(os.path.join(d, "x.node"), nd)
        C.expect_fail("one node x moved by one ulp",
                      lambda: C.same_bytes(prefix + ".node", os.path.join(d, "x.node"))[0])
        fc = T.read_face(prefix + ".face")
        fc.markers[3] = 0
        T.write_face(os.path.join(d, "x.face"), fc)
        C.expect_fail("one face marker changed", lambda: C.same_bytes(prefix + ".face", os.path.join(d, "x.face"))[0])
        for ext, (rd, wr) in RW.items():
            f = rd(prefix + "." + ext)
            out = os.path.join(d, "rt." + ext)
            wr(out, f)
            ok, at = C.same_bytes(prefix + "." + ext, out)
            assert ok, f".{ext} differs at byte {at}"
            assert f.trailer.startswith(b"# Generated by ") and f.newline == b"\r\n"
        print("    node, ele, face, neigh rewritten byte for byte (CRLF + '# Generated by' trailer kept)")


def test_tetgen_counts_match_log():
    """This test fails if the counts the readers return differ from tetgen's own statistics for the same run
    (tetgen_round0.log: mesh points, tetrahedra, faces on input facets), if any element's region attribute is
    not 10 or 20, or if the .neigh file is not symmetric (b in neigh(a) exactly when a in neigh(b)).

    Negative control: the same comparison against the WSL build's log (mesh/chain_proof/logs/tetgen_stp5.log,
    1,605 points and 7,879 tets) must fail."""
    log = _log_stats(os.path.join(C.FIXTURE, "tetgen_round0.log"))
    with C.tmpdir() as d:
        prefix = C.unpack_fixture(d)
        nd, el = T.read_node(prefix + ".node"), T.read_ele(prefix + ".ele")
        fc, nb = T.read_face(prefix + ".face"), T.read_neigh(prefix + ".neigh")
    got = {"points": len(nd.ids), "tets": len(el.ids), "facets": len(fc.ids)}
    wsl = _log_stats(C.repo_file("mesh", "chain_proof", "logs", "tetgen_stp5.log"))
    C.expect_fail("counts against the WSL build's log", lambda: got == {k: wsl[k] for k in got})
    assert got == {k: log[k] for k in got}, (got, log)
    assert set(np.unique(el.attrs[:, 0]).tolist()) == {10.0, 20.0}
    a = np.repeat(np.arange(1, len(el.ids) + 1), 4)
    b = nb.neigh.ravel()
    pairs = set(zip(a[b > 0].tolist(), b[b > 0].tolist()))
    assert all((y, x) in pairs for x, y in pairs), ".neigh is not symmetric"
    hull = int((b < 0).sum())
    assert hull == log["hull"], (hull, log["hull"])
    print(f"    {got} equal tetgen's log; {hull} hull faces (-1 neighbours) = log's {log['hull']}")


def test_poly_roundtrip():
    """This test fails if makeTetraMesh's unseeded output.poly (chain_proof/logs/output.poly.before_seed) is
    not rewritten byte for byte, or if the seeded output.poly does not read as tetgen read it (tetgen log:
    1,346 input points, 2,714 input facets, 2 input regions) with the air seed attribute 10 above the earth seed 20.

    Negative control: rewriting after changing one polygon's first corner must differ from the file."""
    src = C.repo_file("mesh", "chain_proof", "logs", "output.poly.before_seed")
    if not os.path.exists(src):
        src = C.need("chain_proof", "logs", "output.poly.before_seed")
    p = T.read_poly(src)
    with C.tmpdir() as d:
        out = os.path.join(d, "o.poly")
        p.facets[0].polygons[0][0] += 1
        T.write_poly(out, p)
        C.expect_fail("one polygon corner changed", lambda: C.same_bytes(src, out)[0])
        p = T.read_poly(src)
        T.write_poly(out, p)
        ok, at = C.same_bytes(src, out)
        assert ok, f"output.poly differs at byte {at}"
    q = T.read_poly(C.need("chain_proof", "output.poly"))
    log = _log_stats(os.path.join(C.FIXTURE, "tetgen_round0.log"))
    assert (len(q.xyz), len(q.facets), len(q.regions)) == (log["in_points"], log["in_facets"], log["in_regions"])
    air = q.regions[q.regions[:, 3] == 10]
    earth = q.regions[q.regions[:, 3] == 20]
    assert len(air) == 1 and len(earth) == 1 and air[0, 2] < 0 < earth[0, 2], q.regions
    print(f"    unseeded output.poly rewritten byte for byte; seeded file: {len(q.xyz)} points, "
          f"{len(q.facets)} facets, regions {q.regions.tolist()}")


def test_mtr_roundtrip_and_count_check():
    """This test fails if a .mtr written in makeMtr's layout ('%10d%10d' header, '%15.6e' per line) or in
    tetgen's (' %-16.8e') is not read back as the 7- or 9-digit rounded values and rewritten byte for byte, or if
    a .mtr whose header count disagrees with its rows is accepted (tetgen itself ignores such a file and exits 0,
    tetgen.cxx:757-762, so the reader is the only guard).

    Negative control: a file holding one value less than its header claims must be rejected."""
    rng = np.random.default_rng(7)
    v = 10.0 ** rng.uniform(-3, 2, 1000)
    with C.tmpdir() as d:
        p = os.path.join(d, "a.mtr")
        T.write_mtr(p, v, "makemtr")
        lines = open(p, "rb").read().split(b"\n")
        assert lines[0] == b"%10d%10d" % (1000, 1) and len(lines[1]) == 15, lines[:2]
        bad = os.path.join(d, "bad.mtr")
        open(bad, "wb").write(b"\n".join(lines[:-2]) + b"\n")

        def accepted(path):
            T.read_mtr(path)
            return True
        C.expect_fail("header 1000, file holds 999 values", accepted, bad)
        r = T.read_mtr(p)
        assert np.array_equal(r[:, 0], np.array([float("%15.6e" % x) for x in v]))
        T.write_mtr(os.path.join(d, "b.mtr"), r, "makemtr")
        assert C.same_bytes(p, os.path.join(d, "b.mtr"))[0]
        T.write_mtr(os.path.join(d, "t.mtr"), v, "tetgen")
        r2 = T.read_mtr(os.path.join(d, "t.mtr"))
        assert np.array_equal(r2[:, 0], np.array([float("%.8e" % x) for x in v]))
        T.write_mtr(os.path.join(d, "t2.mtr"), r2, "tetgen")
        assert C.same_bytes(os.path.join(d, "t.mtr"), os.path.join(d, "t2.mtr"))[0]
    print("    makeMtr and tetgen .mtr layouts round-trip; wrong-count file rejected")


