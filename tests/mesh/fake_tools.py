"""Fake mesh tools for the chain tests: makeTetraMesh, tetgen, makeMtr and TetGen2Femtic, behaving as the fakes of
hpc/phoenix_plan/tests/run_sh_test.sh do (a 12-tet mesh of the analysis box, cut at z = 0), so that the Python
driver (femtic_mesh.chain) and the kit's mesh_chain.sh can run on the very same tools and be compared.

  python fake_tools.py TOOL ARGS...           (install(bin_dir) writes TOOL.cmd and an sh TOOL wrapper per tool)

Failure switches (environment): FAKE_MTM_ERROR=N (makeTetraMesh logs an error at step N), FAKE_MTM_FAIL=N (exits 1 at
step N), FAKE_TETGEN_FAIL=i (tetgen exits 1 on output.i; 0 = the first run on output.poly), FAKE_MTR_SKIP=i (makeMtr
exits 0 in round i without writing), FAKE_MTR_SHORT=i (one value too few, header included), FAKE_MTR_TRUNC=i (header
right, one row missing: mesh_chain.sh lets it through), FAKE_MTR_FAIL=i (exits 1).
FAKE_CALLS=FILE: every call appends 'TOOL ARGS...' to FILE (the two drivers' call sequences are compared).
"""
import os
import shutil
import sys

TOOLS = ("makeTetraMesh", "tetgen", "makeMtr", "TetGen2Femtic")
TRAILER = "# Generated by tetgen (fake)\n"


def _env(k):
    return os.environ.get(k, "")


def _need(*files):
    for f in files:
        if not (os.path.isfile(f) and os.path.getsize(f)):
            print(f"cannot open {f}")
            sys.exit(1)


def make_tetra_mesh(args):
    if not args or args[0] != "-stp":
        sys.exit(2)
    n = args[1]
    if not (os.path.isfile("control.dat") and os.path.isfile("analysis_domain.dat")):
        open("makeTetraMesh.log", "w").write("cannot open control.dat\n")
        sys.exit(1)
    err = f"Error : fake failure at step {n}\n" if _env("FAKE_MTM_ERROR") == n else ""
    log = f"fake makeTetraMesh -stp {n}\n" + err
    open("makeTetraMesh.log", "w", newline="\n").write(log)
    if _env("FAKE_MTM_FAIL") == n:
        sys.exit(1)
    if n in ("1", "2", "3"):
        open(f"fake.stp{n}", "w", newline="\n").write(f"fake step {n}\n")
    elif n == "4":
        open("output.poly", "w", newline="\n").write("# Part 1 - node list\n0 3 0 0\n# Part 2 - facet list\n0 0\n"
                                                     "# Part 3 - hole list\n0\n# Part 4\n0\n")


def tetgen(args):
    sw, b = args[0], args[-1]
    rnd = "0" if b == "output.poly" else b.split(".", 1)[1]
    if _env("FAKE_TETGEN_FAIL") == rnd:
        print("Out of memory.")
        sys.exit(1)
    if b == "output.poly":
        dom = [ln.split() for ln in open("analysis_domain.dat").read().splitlines()[:3]]
        (x0, x1), (y0, y1), (z0, z1) = [(r[0], r[1]) for r in dom]
        up = lo = None
        lines = open("output.poly").read().splitlines()
        part4 = lines.index("# Part 4")
        for ln in lines[part4 + 2:]:
            f = ln.split()
            if len(f) >= 5:
                if float(f[3]) < 0:
                    up = int(float(f[4]))
                else:
                    lo = int(float(f[4]))
        m = max([v for v in (up, lo) if v is not None] or [0])
        if up is None:
            m += 1
            up = m
        if lo is None:
            lo = m + 1
        with open("output.1.node", "w", newline="\n") as fh:
            fh.write("12 3 0 0\n")
            for iz in range(3):
                for iy in range(2):
                    for ix in range(2):
                        z = z0 if iz == 0 else ("0" if iz == 1 else z1)
                        fh.write(f"{ix + 2 * iy + 4 * iz} {x1 if ix else x0} {y1 if iy else y0} {z}\n")
            fh.write(TRAILER)
        with open("output.1.ele", "w", newline="\n") as fh:
            fh.write("12 4 1\n")
            n = 0
            for k in (0, 1):
                for p in ("012", "021", "102", "120", "201", "210"):
                    c, ids = [0, 0, 0], [4 * k]
                    for a in p:
                        c[int(a)] = 1
                        ids.append(c[0] + 2 * c[1] + 4 * (c[2] + k))
                    fh.write(f"{n} {ids[0]} {ids[1]} {ids[2]} {ids[3]} {lo if k else up}\n")
                    n += 1
            fh.write(TRAILER)
        open("output.1.face", "w", newline="\n").write("0 1\n" + TRAILER)
        open("output.1.neigh", "w", newline="\n").write("12 4\n" + TRAILER)
        print("  Found 2 subdomains.")
        return
    i = int(rnd)
    j = i + 1
    if not all(os.path.isfile(f"{b}.{e}") and os.path.getsize(f"{b}.{e}") for e in ("node", "ele")):
        print("Out of memory.")
        sys.exit(1)
    if "m" in sw and not (os.path.isfile(f"{b}.mtr") and os.path.getsize(f"{b}.mtr")):
        print(f"no {b}.mtr")
        sys.exit(1)
    for e in ("node", "ele", "face", "neigh"):
        shutil.copyfile(f"{b}.{e}", f"output.{j}.{e}")
    nn = int(open(f"{b}.node").readline().split()[0])
    open(f"output.{j}.mtr", "w", newline="\n").write("%10d%10d\n" % (nn, 1) + "%15.6e\n" % 1.5 * nn)
    print(f"fake refinement {b} -> output.{j}")


def make_mtr(args):
    b = args[0]
    i = b.split(".", 1)[1]
    _need("obs_site.dat", "makeMtr.param", f"{b}.node", f"{b}.ele")
    if _env("FAKE_MTR_SKIP") == i:
        print(f"fake makeMtr: round {i} writes nothing")
        return
    if _env("FAKE_MTR_FAIL") == i:
        print(f"fake makeMtr: round {i} fails")
        sys.exit(1)
    n = int(open(f"{b}.node").readline().split()[0]) - (1 if _env("FAKE_MTR_SHORT") == i else 0)
    rows = n - (1 if _env("FAKE_MTR_TRUNC") == i else 0)
    open(f"{b}.mtr", "w", newline="\n").write("%10d%10d\n" % (n, 1) + "%15.6e\n" % 2.0 * rows)
    print(f"fake makeMtr: {b}.mtr")


def _rows(path):
    return [ln.split() for ln in open(path).read().splitlines()[1:] if ln.strip() and not ln.startswith("#")]


def tetgen2femtic(args):
    b = args[0]
    _need(f"{b}.node", f"{b}.ele", "resistivity_attr.dat")
    ra = open("resistivity_attr.dat").read().split("\n")
    na = int(float(ra[0].split()[0]))
    ok = {float(ra[k].split()[0]) for k in range(1, na + 1)}
    air = float(ra[1].split()[0])
    xyz = {int(r[0]): tuple(float(v) for v in r[1:4]) for r in _rows(f"{b}.node")}
    ele = [([int(v) for v in r[1:5]], float(r[5])) for r in _rows(f"{b}.ele")]
    bad = [(e, a) for e, (_, a) in enumerate(ele) if a not in ok]
    if bad:
        print("Region attiribute << %d of element %d cannot be found !!" % (bad[0][1], bad[0][0]))
        sys.exit(1)
    lo = [min(p[d] for p in xyz.values()) for d in range(3)]
    hi = [max(p[d] for p in xyz.values()) for d in range(3)]
    nn, ne = len(xyz), len(ele)
    with open("mesh.dat", "w", newline="\n") as fh:
        fh.write("TETRA\n%10d\n" % nn)
        for i in range(nn):
            fh.write("%10d %20.9e %20.9e %20.9e\n" % (i, *(v * 1000 for v in xyz[i])))
        fh.write("%10d\n" % ne)
        for e, (v, _) in enumerate(ele):
            fh.write("%10d %9d %9d %9d %9d %9d %9d %9d %9d\n" % (e, -1, -1, -1, -1, *v))
        tests = [lambda p, d=d, s=s: p[d] == (hi[d] if s else lo[d]) for d in range(3) for s in (0, 1)]
        for L in range(7):
            lst = []
            for e, (v, a) in enumerate(ele):
                for fc in range(4):
                    pts = [xyz[v[k]] for k in range(4) if k != fc]
                    on = all(p[2] == 0 and a != air for p in pts) if L == 6 else all(tests[L](p) for p in pts)
                    if on:
                        lst.append(f"{e} {fc}")
            fh.write("%10d\n" % len(lst) + "".join(s + "\n" for s in lst))
    cell, nc = [], 1
    for _, a in ele:
        cell.append(0 if a == air else nc)
        nc += a != air
    with open("resistivity_block_iter0.dat", "w", newline="\n") as fh:
        fh.write("%10d%10d\n" % (ne, nc) + "".join("%10d%10d\n" % (e, c) for e, c in enumerate(cell)))
        for c in range(nc):
            fh.write("%10d   %.6e   %.6e   %.6e   %.6e%10d\n" % (c, 100 if c else 1e9, 1e-20, 1e20, 1, 0 if c else 1))
    open(f"{b}.femtic.vtk", "w", newline="\n").write("# vtk DataFile Version 3.0\nfake TetGen2Femtic\nASCII\n")
    print(f"fake TetGen2Femtic: {nn} nodes, {ne} elements, {nc} cells")


def posix(path):
    """C:\\x\\y -> /c/x/y (Git Bash's form; Anaconda's cygpath would map it elsewhere)."""
    p = os.path.abspath(path).replace("\\", "/")
    return "/" + p[0].lower() + p[2:] if len(p) > 1 and p[1] == ":" else p


def install(bin_dir, python=sys.executable):
    """Write the four fakes into bin_dir: TOOL.cmd (Windows) and an executable sh script TOOL (Git Bash, Linux)."""
    os.makedirs(bin_dir, exist_ok=True)
    me = os.path.abspath(__file__)
    fwd = (lambda p: p.replace("\\", "/")) if os.name == "nt" else (lambda p: p)   # Git Bash runs C:/... as given
    for t in TOOLS:
        with open(os.path.join(bin_dir, t), "w", newline="\n") as fh:
            fh.write(f'#!/bin/sh\nexec "{fwd(python)}" "{fwd(me)}" {t} "$@"\n')
        os.chmod(os.path.join(bin_dir, t), 0o755)
        if os.name == "nt":
            with open(os.path.join(bin_dir, t + ".cmd"), "w", newline="\r\n") as fh:
                fh.write(f'@"{python}" "{me}" {t} %*\n@exit /b %ERRORLEVEL%\n')
    return bin_dir


if __name__ == "__main__":
    tool, args = sys.argv[1], sys.argv[2:]
    if _env("FAKE_CALLS"):
        with open(_env("FAKE_CALLS"), "a", newline="\n") as fh:
            fh.write(" ".join([tool] + args) + "\n")
    run = {"makeTetraMesh": make_tetra_mesh, "tetgen": tetgen, "makeMtr": make_mtr, "TetGen2Femtic": tetgen2femtic}
    run[tool](args)
